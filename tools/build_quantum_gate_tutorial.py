"""Build matching Markdown and self-contained Typst from tutorial content."""

import json
from pathlib import Path

from render_typst_report import inline


ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "research" / "quantum_gate_review_20261029"


def keep_heading_with_opening(lines):
    """Keep a heading, source note and first paragraph/equation together."""
    result, i = [], 0
    while i < len(lines):
        if lines[i].startswith("= ") or lines[i].startswith("== "):
            group = ["#block(breakable: false)["]
            while i < len(lines):
                line = lines[i]
                group.append(line)
                i += 1
                if line.startswith(("#text(\"", "$ ", "#strong[")):
                    break
            result.extend(group + ["]", ""])
        else:
            result.append(lines[i])
            i += 1
    return result


def main():
    content = json.loads((FOLDER / "QuantumGate_tutorial_content.json").read_text(encoding="utf-8"))
    title = content["title"]
    md = ["# " + title, "", content["subtitle"], ""]
    typ = [r'''// Self-contained teaching edition; generated by tools/build_quantum_gate_tutorial.py.
// Chinese: KaiTi. English: Times New Roman. Compile with Typst 0.11.1 or later.
#set document(title: "QuantumGate 逐节教学讲义")
#set page(paper: "a4", margin: (x: 23mm, y: 22mm), numbering: "1", number-align: center,
  header: align(right, text(size: 8pt, fill: rgb("666666"))[QuantumGate · 逐节教学讲义]))
#set text(font: ("Times New Roman", "KaiTi"), size: 11pt, lang: "zh")
#set par(justify: true, leading: 0.65em)
#set heading(numbering: "1.1")
#show heading.where(level: 1): it => {
  set text(size: 16pt, weight: "bold")
  it
}
#show heading.where(level: 2): set text(size: 12pt, weight: "bold")
#show math.equation: set text(font: "New Computer Modern Math")
#show link: set text(fill: rgb("244a69"))
#let question(n, body) = block(inset: 9pt, fill: rgb("f3f5f6"), breakable: true)[
  *练习 #n* #body
]
''', "#align(center)[#text(size: 22pt, weight: \"bold\")[" + inline(title) + "]]",
           "#align(center)[" + inline(content["subtitle"]) + "]", "#v(1em)"]
    for paragraph in content["guide"]:
        md.extend([paragraph, ""])
        typ.extend([inline(paragraph), ""])
    typ.extend(['#outline(title: [阅读导航], depth: 1)', '#pagebreak()'])
    answers = []
    counts = {"chapters": 0, "examples": 0, "equations": 0, "exercises": 0}
    for chapter in content["chapters"]:
        counts["chapters"] += 1
        md.extend(["## " + chapter["title"], "", "对应原报告：" + chapter["source"], ""])
        typ.extend(["= " + chapter["title"], "", "#text(size: 9pt, fill: rgb(\"555555\"))[" + inline("对应原报告：" + chapter["source"]) + "]", ""])
        for block in chapter["blocks"]:
            kind = block["type"]
            if kind == "paragraph":
                md.extend([block["text"], ""])
                typ.extend([inline(block["text"]), ""])
            elif kind in {"section", "example"}:
                heading = ("手算例：" if kind == "example" else "") + block["title"]
                counts["examples"] += kind == "example"
                md.extend(["### " + heading, ""])
                typ.extend(["== " + heading, ""])
            elif kind == "equation":
                counts["equations"] += 1
                md.extend(["$$", block["latex"], "$$", ""])
                typ.extend(["$ " + block["typst"] + " $", ""])
            elif kind == "exercise":
                counts["exercises"] += 1
                n = counts["exercises"]
                md.extend([f"**练习 {n}**　" + block["question"], ""])
                typ.extend([f"#question({n})[" + inline(block["question"]) + "]", ""])
                answers.append((n, block["question"], block["answer"]))
            else:
                raise ValueError(kind)
    md.extend(["## 练习答案与讲解", ""])
    typ.extend(["#pagebreak()", "= 练习答案与讲解", ""])
    for number, question, answer in answers:
        md.extend([f"### 练习 {number}", "", question, "", answer, ""])
        typ.extend([f"== 练习 {number}", "", inline(question), "", inline(answer), ""])
    md.extend(["## 延伸阅读", ""])
    typ.extend(["= 延伸阅读", ""])
    for entry in content["reading"]:
        md.extend([entry, ""])
        typ.extend([inline(entry), ""])
    (FOLDER / "QuantumGate_tutorial.md").write_text("\n".join(md), encoding="utf-8")
    (FOLDER / "QuantumGate_tutorial.typ").write_text("\n".join(keep_heading_with_opening(typ)), encoding="utf-8")
    print(json.dumps(counts, ensure_ascii=False))


if __name__ == "__main__":
    main()
